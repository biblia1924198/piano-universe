"""Configure confirmed launch addresses; never invent a Pix payment code."""
from pathlib import Path
import argparse,json,re
root=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser()
p.add_argument('--repository',required=True,help='usuario/repositorio')
p.add_argument('--pix-payload-file',type=Path,help='Pix Copia e Cola generated by the bank')
p.add_argument('--publish-ready',action='store_true',help='Remove the review banner after maintainer approval')
a=p.parse_args()
if not re.fullmatch(r'[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+',a.repository):raise SystemExit('Repositorio invalido')
cfg=json.loads((root/'docs/site-config.json').read_text())
cfg['repository']=a.repository
cfg['releaseUrl']='https://github.com/'+a.repository+'/releases/download/v0.27-preview1/Piano-Universe-v0.27-preview1.apk'
if a.pix_payload_file:
 payload=a.pix_payload_file.read_text(encoding='utf-8-sig').strip()
 if not payload.startswith('000201') or len(payload)>1024 or payload[-8:-4]!='6304':raise SystemExit('Payload Pix invalido')
 crc=0xffff
 for byte in payload[:-4].encode('utf-8'):
  crc^=byte<<8
  for _ in range(8):crc=((crc<<1)^0x1021)&0xffff if crc&0x8000 else (crc<<1)&0xffff
 if f'{crc:04X}'!=payload[-4:].upper():raise SystemExit('CRC do Pix invalido')
 cfg['pixPayload']=payload
if a.publish_ready:
 if not cfg.get('pixPayload'):print('Pix ainda desativado; o site mostrara apoio em breve.')
 cfg['preview']=False
else:cfg['preview']=True
for name,data in [('site-config.json',json.dumps(cfg,ensure_ascii=False,indent=2)),('site-config.js','window.PIANO_UNIVERSE='+json.dumps(cfg,ensure_ascii=False)+';')]:
 (root/'docs'/name).write_text(data,encoding='utf-8')
(root/'.github/FUNDING.yml').write_text('custom: ["https://'+a.repository.split('/')[0]+'.github.io/'+a.repository.split('/')[1]+'/#apoie"]\n',encoding='utf-8')
print('Enderecos oficiais configurados; confira o beneficiario do Pix antes de publicar.')
